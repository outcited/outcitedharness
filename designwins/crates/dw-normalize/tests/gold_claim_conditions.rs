use std::path::PathBuf;

use dw_normalize::parse_condition;
use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct ClaimCondition {
    condition_verbatim: String,
    /// How many claims carry this condition. The corpus is weighted: one
    /// condition on 4,000 claims matters 4,000× a one-off.
    claim_count: u64,
    expected: serde_json::Value,
}

fn repo_root() -> PathBuf {
    let mut dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    loop {
        if dir.join("tests").join("fixtures").join("gold").is_dir() {
            return dir;
        }
        assert!(dir.pop(), "could not locate tests/fixtures/gold");
    }
}

fn corpus_path() -> PathBuf {
    repo_root()
        .join("tests")
        .join("fixtures")
        .join("gold")
        .join("claim_conditions_v1.jsonl")
}

fn values_match(a: &serde_json::Value, b: &serde_json::Value) -> bool {
    use serde_json::Value;
    match (a, b) {
        (Value::Number(x), Value::Number(y)) => {
            let (Some(x), Some(y)) = (x.as_f64(), y.as_f64()) else {
                return x == y;
            };
            let scale = 1.0_f64.max(x.abs()).max(y.abs());
            (x - y).abs() <= 1e-12 * scale
        }
        (Value::Object(x), Value::Object(y)) => {
            x.len() == y.len()
                && x.iter()
                    .all(|(k, v)| y.get(k).is_some_and(|w| values_match(v, w)))
        }
        (Value::Array(x), Value::Array(y)) => {
            x.len() == y.len() && x.iter().zip(y.iter()).all(|(u, v)| values_match(u, v))
        }
        _ => a == b,
    }
}

fn canonical(v: &serde_json::Value) -> serde_json::Value {
    match v {
        serde_json::Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let mut out = serde_json::Map::new();
            for k in keys {
                out.insert(k.clone(), canonical(&map[k]));
            }
            serde_json::Value::Object(out)
        }
        serde_json::Value::Array(items) => {
            serde_json::Value::Array(items.iter().map(canonical).collect())
        }
        other => other.clone(),
    }
}

#[test]
fn gold_claim_conditions_10270() {
    let text = std::fs::read_to_string(corpus_path()).expect("corpus present");
    let rows: Vec<ClaimCondition> = text
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str(l).expect("row parses"))
        .collect();

    assert_eq!(rows.len(), 10270, "corpus cardinality");
    let total_claims: u64 = rows.iter().map(|r| r.claim_count).sum();
    assert_eq!(total_claims, 64245, "claims covered");

    let mut passed = 0usize;
    let mut failed = 0usize;
    let mut claims_passed = 0u64;
    let mut claims_failed = 0u64;
    let mut failures: Vec<String> = Vec::new();

    for row in &rows {
        let outcome = parse_condition(&row.condition_verbatim);
        let actual = serde_json::to_value(&outcome).expect("serialises");
        if values_match(&canonical(&actual), &canonical(&row.expected)) {
            passed += 1;
            claims_passed += row.claim_count;
        } else {
            failed += 1;
            claims_failed += row.claim_count;
            if failures.len() < 15 {
                failures.push(format!(
                    "x{} verbatim={:?}\n    expected {}\n    actual   {}",
                    row.claim_count,
                    row.condition_verbatim,
                    serde_json::to_string(&canonical(&row.expected)).expect("json"),
                    serde_json::to_string(&canonical(&actual)).expect("json"),
                ));
            }
        }
    }

    for f in &failures {
        eprintln!("{f}");
    }
    if failed > 15 {
        eprintln!("… and {} more", failed - 15);
    }

    eprintln!(
        "\nN4b claim_conditions: {passed}/{len} distinct, {claims_passed}/{total} claims weighted",
        len = rows.len(),
        total = total_claims
    );
    eprintln!("  distinct failed  {failed}");
    eprintln!("  claims affected  {claims_failed}");

    // Both bars: the distinct conditions and, separately, the claims those
    // conditions carry. A single divergent condition on 4,000 claims is not
    // the same event as a one-off.
    assert_eq!(
        passed,
        rows.len(),
        "Gate N4b requires every distinct condition to match. \
         Divergence is a ledger entry (D2), never a re-specification."
    );
    assert_eq!(claims_failed, 0, "no claim may be affected by a divergence");
}

/// The provenance shape must satisfy `C3`/`C13` — every claim carries a quote
/// and a document hash. This is what makes "every number opens to the page"
/// possible downstream.
#[test]
fn claim_provenance_has_c3_shape() {
    let path = repo_root()
        .join("tests")
        .join("fixtures")
        .join("gold")
        .join("claim_provenance_v1.jsonl");
    let text = std::fs::read_to_string(&path).expect("provenance corpus present");

    let mut total = 0usize;
    let mut with_quote = 0usize;
    let mut with_sha = 0usize;
    let mut with_page = 0usize;

    for line in text.lines().filter(|l| !l.trim().is_empty()) {
        let v: serde_json::Value = serde_json::from_str(line).expect("row");
        total += 1;
        if v.get("quote")
            .and_then(|q| q.as_str())
            .is_some_and(|q| !q.is_empty())
        {
            with_quote += 1;
        }
        if v.get("doc_sha256")
            .and_then(|q| q.as_str())
            .is_some_and(|q| !q.is_empty())
        {
            with_sha += 1;
        }
        if v.get("page").is_some() {
            with_page += 1;
        }
    }

    eprintln!(
        "claim_provenance: {total} rows, quote {with_quote}, sha {with_sha}, page {with_page}"
    );
    assert_eq!(total, 86736, "the full claim corpus");
    assert_eq!(
        with_sha, total,
        "C1: every claim joins to the vault on sha256"
    );
    // Quote and page are the C13 path. They are not universal in the corpus
    // yet, so this asserts the floor rather than perfection, and reports the
    // real number instead of hiding it.
    assert!(
        with_quote >= total * 9 / 10,
        "C3: at least 90% of claims must carry a verbatim quote; got {with_quote}/{total}"
    );
}
